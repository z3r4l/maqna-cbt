import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const browser=await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE ?? 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless:true });
try {
 const page=await browser.newPage({viewport:{width:390,height:800}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173/login');
 await page.locator('input[autocomplete="username"]').fill('teacher_demo');
 await page.locator('input[autocomplete="current-password"]').fill('FixtureOnly123!');
 await page.getByRole('button',{name:'Masuk'}).click();
 await page.getByRole('heading',{name:/Selamat datang/}).waitFor();
 await page.goto('http://127.0.0.1:5173/questions/new');
 await page.getByRole('heading',{name:'Tulis soal'}).waitFor();
 const editor=page.getByRole('textbox',{name:'Pertanyaan'});
 await editor.waitFor();
 await editor.fill('Berapa $2+2$?');
 await editor.fill('Soal kedua $3+3$?');
 assert.match(await editor.innerText(),/Soal kedua/);
 assert.deepEqual(errors,[]);
 await page.goto('http://127.0.0.1:5173/exams/new');
 await page.getByRole('heading',{name:'Buat ujian'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Pilih tanggal mulai'}).count(),1);
 assert.equal(await page.getByRole('button',{name:'Pilih tanggal selesai'}).count(),1);
 assert.equal(await page.locator('input[type="time"]').count(),2);
 await page.getByRole('button',{name:'Pilih tanggal mulai'}).click();
 await page.getByRole('button',{name:'Bulan berikutnya'}).waitFor();
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('button',{name:'Pilih tanggal mulai'}).evaluate(node => node === document.activeElement),true);
 await page.getByRole('button',{name:'Pilih tanggal mulai'}).click();
 const today=new Date();
 const names=['Januari','Februari','Maret','April','Mei','Juni','Juli','Agustus','September','Oktober','November','Desember'];
 await page.getByRole('button',{name:`${today.getDate()} ${names[today.getMonth()]} ${today.getFullYear()}`}).click();
 await page.getByLabel('Jam mulai').fill('08:00');
 assert.match(await page.getByRole('button',{name:'Pilih tanggal mulai'}).innerText(),new RegExp(`${today.getDate()} ${names[today.getMonth()]}`));
 await page.setViewportSize({width:320,height:800});
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false,'date picker overflow at 320px');
 const admin=await browser.newPage();
 await admin.goto('http://127.0.0.1:5173/login');
 await admin.locator('input[autocomplete="username"]').fill('admin_demo');
 await admin.locator('input[autocomplete="current-password"]').fill('FixtureOnly123!');
 await admin.getByRole('button',{name:'Masuk'}).click();
 await admin.getByRole('heading',{name:/Selamat datang/}).waitFor();
 await admin.goto('http://127.0.0.1:5173/questions/391');
 await admin.getByRole('heading',{name:'Soal dan pratinjau'}).waitFor();
 await admin.getByRole('textbox',{name:'Pertanyaan'}).waitFor();
 await admin.waitForFunction(() => (document.querySelector('[contenteditable][aria-label="Pertanyaan"]')?.textContent ?? '').trim().length > 0);
 assert.ok(await admin.locator('.question-editor-content .tiptap').count() >= 1);
 assert.equal(await admin.locator('.ck-editor').count(),0);
 assert.ok((await admin.getByRole('textbox',{name:'Pertanyaan'}).innerText()).trim().length > 0);
 console.log('Tiptap question editor and exam date pickers PASS');
} finally { await browser.close(); }
